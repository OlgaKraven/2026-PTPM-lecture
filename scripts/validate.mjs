import fs from 'node:fs'
import assert from 'node:assert/strict'
import {validateCourse} from '@olgakraven/lecture-engine'
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'))
const c=read('public/course.json'),p=read('public/teaching/notes.json'),a=read('public/assessment.json'),supplements=read('public/question-supplements.json')
validateCourse(c)
assert.equal(c.lectures.length,8)
assert.deepEqual(c.semesters,[4,5])
const ids=new Set()
for(const l of c.lectures){
 assert.equal(l.slides.filter(s=>s.kind==='section').length,3)
 assert.equal(l.slides.filter(s=>s.activityPassport).length,3)
 assert.deepEqual(l.slides.slice(0,5).map(s=>s.kind),['title','literature','literature','materials','agenda'])
 assert.equal(l.slides.at(-1).kind,'questions')
 const starts=l.slides.flatMap((s,i)=>s.kind==='section'?[i]:[])
 for(let q=0;q<starts.length;q++){
  const block=l.slides.slice(starts[q],starts[q+1]||l.slides.length-1)
  assert.deepEqual(block.filter(s=>s.task).map(s=>s.task.type),['single','multiple','short','matching'])
  const passport=block.findIndex(s=>s.activityPassport),firstTest=block.findIndex(s=>s.task)
  assert.equal(passport,firstTest-1)
  assert(block.some(s=>s.kicker.startsWith('Разбор изменённого')))
  assert(block.some(s=>s.kind==='warning'))
  assert(block.some(s=>s.notebook))
 }
 for(const s of l.slides){
  assert(!ids.has(s.id));ids.add(s.id)
  assert(p.notes[s.id],s.id)
  assert(p.notes[s.id].script.trim(),s.id)
  assert.equal(p.notes[s.id].notebook,s.notebook||'')
  if(s.task){
   const key=a.keys[s.task.id];assert(key)
   const options=s.task.options||[]
   assert.equal(key.type,s.task.type)
   if(s.task.type==='single'||s.task.type==='multiple'){
    assert(key.correct.every(id=>options.some(o=>o.id===id)))
    assert.equal(options.length,s.task.type==='single'?4:5)
    if(s.task.type==='multiple')assert.equal(s.task.choose,key.correct.length)
   }
   if(s.task.type==='short')assert(key.numeric||key.accepted?.length)
   if(s.task.type==='matching'){
    assert.equal(s.task.items.length,4);assert.equal(options.length,4)
    assert(s.task.items.every(item=>options.some(o=>o.id===key.pairs[item.id])))
   }
  }
  if(s.rows)for(const row of s.rows)assert.equal(row.length,s.columns.length)
  for(const field of ['title','body','kicker','notebook'])assert(!/Generated by|Co-authored-by|сборка курса|версия содержания/i.test(s[field]||''))
 }
 assert.equal(l.slides.reduce((t,s)=>t+p.notes[s.id].estimatedSeconds,0),5400)
}
assert.equal(ids.size,Object.keys(p.notes).length)
assert.equal(c.id,p.courseId);assert.equal(c.contentVersion,p.contentVersion)
assert.equal(supplements.activities.length,24)
for(const activity of supplements.activities){assert(activity.options[activity.correct]);assert(activity.solution.trim());assert(activity.exerciseSpec.scenarios[0].frames.length>1)}
for(const path of [c.logo,c.mascot,c.font,c.topicArrow])assert(fs.existsSync(`public/${path}`),path)
console.log(`Validated ${ids.size} slides and notes, ${Object.keys(a.keys).length} assessment keys`)
