import fs from 'node:fs'
import assert from 'node:assert/strict'
import {validateCourse} from '@olgakraven/lecture-engine'
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'))
const c=read('public/course.json'),p=read('public/teaching/notes.json'),a=read('public/assessment.json')
validateCourse(c)
assert.equal(c.lectures.length,8)
assert.deepEqual(c.semesters,[4,5])
const ids=new Set()
for(const l of c.lectures){
 assert.equal(l.slides.filter(s=>s.kind==='section').length,3)
 assert.equal(l.slides.filter(s=>s.kicker==='Самостоятельный разбор').length,3)
 for(const s of l.slides){
  assert(!ids.has(s.id));ids.add(s.id)
  assert(p.notes[s.id],s.id)
  assert(p.notes[s.id].script.trim(),s.id)
  assert.equal(p.notes[s.id].notebook,s.notebook||'')
  if(s.task){assert(a.keys[s.task.id]);assert(s.task.options.some(o=>a.keys[s.task.id].correct.includes(o.id)))}
  if(s.rows)for(const row of s.rows)assert.equal(row.length,s.columns.length)
  for(const field of ['title','body','kicker','notebook'])assert(!/Generated by|Co-authored-by|сборка курса|версия содержания/i.test(s[field]||''))
 }
 assert.equal(l.slides.reduce((t,s)=>t+p.notes[s.id].estimatedSeconds,0),5400)
}
assert.equal(ids.size,Object.keys(p.notes).length)
assert.equal(c.id,p.courseId);assert.equal(c.contentVersion,p.contentVersion)
for(const path of [c.logo,c.mascot,c.font,c.topicArrow])assert(fs.existsSync(`public/${path}`),path)
console.log(`Validated ${ids.size} slides and notes, ${Object.keys(a.keys).length} assessment keys`)
